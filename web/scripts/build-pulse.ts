// Builds public/pulse.json: this week's headline numbers from the tracker's latest
// weekly snapshot, for the "this week" strip on vfaraji89.github.io (same origin).
// Runs before every build (data step). Generated, not committed.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const dir = new URL("../../market/weekly/", import.meta.url);
const weeks = readdirSync(dir).filter((f) => /^\d{4}-W\d{2}\.json$/.test(f)).sort();
const latest = weeks[weeks.length - 1];
const market = JSON.parse(readFileSync(new URL("../src/data/market.json", import.meta.url), "utf8"));
const boards = (market.sources ?? []).reduce((a: number, s: { boards?: number }) => a + (s.boards ?? 1), 0);
let out: Record<string, unknown> = { note: "Generated by web/scripts/build-pulse.ts. Do not edit.", boards };
if (latest) {
  const w = JSON.parse(readFileSync(new URL(latest, dir), "utf8"));
  out = { ...out, week: w.week, from: w.from, to: w.to, open: w.open, new: w.new, remoteShare: w.remoteShare };
}
writeFileSync(new URL("../public/pulse.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log(`pulse.json: ${out.week ?? "no week"}, ${out.open ?? "?"} open, ${boards} boards`);
